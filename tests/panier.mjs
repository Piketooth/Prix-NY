import { chromium } from 'playwright';
const out = process.argv[2];
const scheme = process.argv[3] || 'light';
const b = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, colorScheme: scheme, hasTouch: false });
await ctx.addInitScript(() => { try { sessionStorage.setItem('splash', '1'); if (!localStorage.getItem('s5')) { localStorage.setItem('s5', '1'); localStorage.setItem('settings', JSON.stringify({ wallpaper: 'central-park', wpInterval: 'launch' })); } } catch {} });
const p = await ctx.newPage();
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !/net::|Failed to load|404/.test(m.text()) && errs.push(m.text()));
await p.route('https://api.frankfurter.dev/**', r => r.fulfill({ json: { amount: 1, base: 'USD', date: '2026-10-16', rates: { EUR: 0.9 } } }));
await p.route('https://open.er-api.com/**', r => r.abort());
await p.goto('http://localhost:8765/');
await p.waitForFunction(() => document.getElementById('rate-info').textContent.includes('0,9'));
await p.waitForTimeout(1800);
const ok = (label, cond) => console.log(cond ? 'OK  ' : 'FAIL', label);
const key = async (k) => { await p.locator(`#kbd [data-key="${k}"]`).first().dispatchEvent('pointerdown'); await p.locator(`#kbd [data-key="${k}"]`).first().dispatchEvent('pointerup'); };
const typeK = async (s) => { for (const ch of s) await key(ch === ' ' ? 'space' : ch.toLowerCase()); };

ok('pas de bouton ↺', !(await p.$('#reset-btn')));
ok('pas de skyline', !(await p.$('.skyline')));
ok('fond affiché', await p.evaluate(() => document.body.classList.contains('has-wp') && getComputedStyle(document.querySelector('.wp-layer.on')).backgroundImage.includes('central-park')));
await p.screenshot({ path: `${out}/v5-main-${scheme}.png` });
// Clavier maison sur le nom de l'article
await p.click('#item-name');
await p.waitForTimeout(400);
ok('clavier ouvert', await p.isVisible('#kbd'));
ok('pavé fermé', !(await p.isVisible('#keypad')));
await typeK('casqutte');
await p.waitForTimeout(200);
const sugs = await p.$$eval('.kbd-sug', (l) => l.map((x) => x.textContent));
ok(`suggestions: ${sugs}`, sugs[0] === 'Casquette');
await key('space');
ok(`correction: "${await p.inputValue('#item-name')}"`, (await p.inputValue('#item-name')) === 'Casquette ');
await key('back');
ok(`annulation: "${await p.inputValue('#item-name')}"`, (await p.inputValue('#item-name')) === 'Casqutte ');
await key('back'); for (let i = 0; i < 8; i++) await key('back');
// accents par appui long
await p.locator('#kbd [data-key="e"]').dispatchEvent('pointerdown'); await p.waitForTimeout(500);
ok('popup accents', await p.isVisible('.kbd-popup'));
await p.click('.kbd-popup .kbd-key:has-text("É")');
await typeK('te');
ok(`accent + majuscule auto: "${await p.inputValue('#item-name')}"`, (await p.inputValue('#item-name')) === 'Éte');
await key('space');
ok(`accent ajouté à l'espace: "${await p.inputValue('#item-name')}"`, (await p.inputValue('#item-name')) === 'Été ');
await typeK('pharmacie'); await key('space');
await key('123'); await key('4'); await key('abc');
ok(`chiffres: "${await p.inputValue('#item-name')}"`, (await p.inputValue('#item-name')).endsWith('4'));
await p.screenshot({ path: `${out}/v5-kbd-${scheme}.png` });
// bascule vers le pavé numérique en touchant le prix
await p.click('#price'); await p.waitForTimeout(300);
ok('pavé ouvert, clavier fermé', (await p.isVisible('#keypad')) && !(await p.isVisible('#kbd')));
await p.click('[data-key="2"]'); await p.click('[data-key="5"]');
await p.goBack(); await p.waitForTimeout(250);
ok('retour ferme le pavé', !(await p.isVisible('#keypad')));
await p.click('#add-btn'); await p.waitForTimeout(1200);
// Fenêtre d'enregistrement avec clavier
await p.click('#cart-open'); await p.waitForTimeout(400);
await p.screenshot({ path: `${out}/v5-cart-${scheme}.png` });
await p.click('#cart-save'); await p.waitForTimeout(300);
await p.waitForTimeout(300);
ok('clavier dans la fenêtre', await p.evaluate(() => document.getElementById('kbd').closest('dialog') !== null && !document.getElementById('kbd').hidden));
await key('back');
await typeK('soho');
ok(`frappe dans la fenêtre: "${await p.inputValue('#name-input')}"`, (await p.inputValue('#name-input')) === 'Soho');
await p.screenshot({ path: `${out}/v5-dialog-${scheme}.png` });
await key('ok'); await p.waitForTimeout(200);
await p.click('#name-dialog button[value=ok]'); await p.waitForTimeout(200);
await p.goBack(); await p.waitForTimeout(250);
// Réglages : galerie
await p.click('#settings-open'); await p.waitForTimeout(400);
const tiles = await p.$$eval('.wp-tile', (l) => l.map((t) => t.textContent));
ok(`galerie: ${tiles.length} vignettes`, tiles.length === 11);
await p.click('.wp-tile:has-text("Aléatoire")');
ok('délais visibles en aléatoire', await p.isVisible('#wp-interval'));
await p.click('#wp-interval .chip:has-text("30 s")');
const st = await p.evaluate(() => JSON.parse(localStorage.getItem('settings')));
ok(`réglage: ${st.wallpaper} / ${st.wpInterval}`, st.wallpaper === 'random' && st.wpInterval === 30);
await p.click('.wp-tile:has-text("Taxis")'); await p.waitForTimeout(1800);
ok('fond Taxis', await p.evaluate(() => getComputedStyle(document.querySelector('.wp-layer.on')).backgroundImage.includes('taxis')));
ok('délais masqués hors aléatoire', !(await p.isVisible('#wp-interval')));
await p.evaluate(() => document.querySelector('#settings-view').scrollTo(0, 99999));
await p.evaluate(() => document.querySelector('.settings').scrollTop = 99999);
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/v5-settings-${scheme}.png` });
ok(`${scheme} erreurs JS: ${errs}`, errs.length === 0);
await b.close();
